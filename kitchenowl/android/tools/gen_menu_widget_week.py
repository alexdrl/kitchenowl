"""Usage: python gen_menu_widget_week.py ../app/src/main/res/layout/menu_widget_week.xml

Generates res/layout/menu_widget_week.xml (Monday-Sunday rows x lunch/dinner/other)."""
import sys

# No breakfast: the week table is for the main meals.
MEALS = ["lunch", "dinner", "any"]
HEADER_LABELS = {
    "breakfast": "@string/menu_widget_breakfast",
    "lunch": "@string/menu_widget_lunch",
    "dinner": "@string/menu_widget_dinner",
    "any": "@string/menu_widget_other",
}

out = []
w = out.append
w('<?xml version="1.0" encoding="utf-8"?>')
w('<!-- Current week (Monday-Sunday) for big widgets (tablets). Generated by')
w('     android/tools/gen_menu_widget_week.py: 7 rows x lunch/dinner/other; MenuWidgetProvider.kt fills')
w('     it, highlights today and hides the "other" column when unused.')
w('     Only classes RemoteViews allows (no plain View). -->')
w('<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"')
w('    android:id="@+id/menu_widget_root"')
w('    android:layout_width="match_parent"')
w('    android:layout_height="match_parent"')
w('    android:background="@drawable/menu_widget_background"')
w('    android:orientation="vertical"')
w('    android:padding="14dp">')
w('    <TextView')
w('        android:id="@+id/menu_widget_date"')
w('        android:layout_width="match_parent"')
w('        android:layout_height="wrap_content"')
w('        android:maxLines="1"')
w('        android:text="@string/menu_widget_week_title"')
w('        android:textColor="@color/menu_widget_text"')
w('        android:textSize="15sp"')
w('        android:textStyle="bold" />')
# column headers
w('    <LinearLayout')
w('        android:layout_width="match_parent"')
w('        android:layout_height="wrap_content"')
w('        android:layout_marginTop="6dp"')
w('        android:orientation="horizontal">')
w('        <TextView')
w('            android:layout_width="56dp"')
w('            android:layout_height="wrap_content" />')
for m in MEALS:
    w('        <TextView')
    w(f'            android:id="@+id/menu_widget_week_head_{m}"')
    w('            android:layout_width="0dp"')
    w('            android:layout_height="wrap_content"')
    w('            android:layout_weight="1"')
    w('            android:paddingStart="6dp"')
    w(f'            android:text="{HEADER_LABELS[m]}"')
    w('            android:textColor="@color/menu_widget_accent"')
    w('            android:textSize="12sp"')
    w('            android:textStyle="bold" />')
w('    </LinearLayout>')
for d in range(7):
    w('    <LinearLayout')
    w(f'        android:id="@+id/menu_widget_week_row{d}"')
    w('        android:layout_width="match_parent"')
    w('        android:layout_height="0dp"')
    w('        android:layout_marginTop="2dp"')
    w('        android:layout_weight="1"')
    w('        android:gravity="center_vertical"')
    w('        android:orientation="horizontal"')
    w('        android:paddingTop="2dp"')
    w('        android:paddingBottom="2dp">')
    w('        <TextView')
    w(f'            android:id="@+id/menu_widget_week_day{d}"')
    w('            android:layout_width="56dp"')
    w('            android:layout_height="wrap_content"')
    w('            android:paddingStart="6dp"')
    w('            android:maxLines="2"')
    w('            android:textColor="@color/menu_widget_text"')
    w('            android:textSize="12sp"')
    w('            />')
    for m in MEALS:
        w('        <TextView')
        w(f'            android:id="@+id/menu_widget_week_{m}{d}"')
        w('            android:layout_width="0dp"')
        w('            android:layout_height="wrap_content"')
        w('            android:layout_weight="1"')
        w('            android:ellipsize="end"')
        w('            android:maxLines="2"')
        w('            android:paddingStart="6dp"')
        w('            android:paddingEnd="2dp"')
        w('            android:textColor="@color/menu_widget_text"')
        w('            android:textSize="12sp" />')
    w('    </LinearLayout>')
w('    <TextView')
w('        android:id="@+id/menu_widget_updated"')
w('        android:layout_width="match_parent"')
w('        android:layout_height="wrap_content"')
w('        android:layout_marginTop="4dp"')
w('        android:maxLines="1"')
w('        android:textColor="@color/menu_widget_text_secondary"')
w('        android:textSize="10sp"')
w('        android:visibility="gone" />')
w('</LinearLayout>')

with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
